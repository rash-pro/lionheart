"""Embed approved host fonts/emblem; output is build-only, no game data."""
import argparse
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]


def rgba_png(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("expected PNG")
    offset, chunks = 8, bytearray()
    while offset < len(data):
        length = struct.unpack_from(">I", data, offset)[0]
        kind = data[offset + 4:offset + 8]
        chunk = data[offset + 8:offset + 8 + length]
        if kind == b"IHDR":
            width, height, bits, colour, _, _, interlace = struct.unpack(">IIBBBBB", chunk)
            if bits != 8 or colour not in (2, 6) or interlace:
                raise ValueError("expected noninterlaced RGB/RGBA8")
        elif kind == b"IDAT":
            chunks.extend(chunk)
        offset += length + 12
    channels = 4 if colour == 6 else 3
    stride = width * channels
    raw = zlib.decompress(chunks)
    previous = bytearray(stride)
    pixels = bytearray()
    for y in range(height):
        at = y * (stride + 1)
        mode = raw[at]
        row = bytearray(raw[at + 1:at + 1 + stride])
        for x in range(stride):
            left = row[x - channels] if x >= channels else 0
            up = previous[x]
            upper_left = previous[x - channels] if x >= channels else 0
            if mode == 1:
                row[x] = (row[x] + left) & 255
            elif mode == 2:
                row[x] = (row[x] + up) & 255
            elif mode == 3:
                row[x] = (row[x] + ((left + up) // 2)) & 255
            elif mode == 4:
                p = left + up - upper_left
                distances = [abs(p - left), abs(p - up), abs(p - upper_left)]
                predictor = (left, up, upper_left)[distances.index(min(distances))]
                row[x] = (row[x] + predictor) & 255
            elif mode != 0:
                raise ValueError("invalid PNG filter")
        for x in range(width):
            pixels.extend(row[x * channels:x * channels + 3])
            pixels.append(row[x * channels + 3] if channels == 4 else 255)
        previous = row
    return width, height, pixels


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    width, height, emblem = rgba_png(ROOT / "assets/branding/icon-128.png")
    blobs = {
        "gui_font_regular": (ROOT / "third_party/chakra-petch/ChakraPetch-Regular.ttf").read_bytes(),
        "gui_font_semibold": (ROOT / "third_party/chakra-petch/ChakraPetch-SemiBold.ttf").read_bytes(),
        "gui_emblem_rgba": emblem,
    }
    lines = ["/* Generated by tools/embed_gui_assets.py; source notices accompany vendored assets. */",
             "#ifndef FF8_GUI_ASSETS_H", "#define FF8_GUI_ASSETS_H",
             f"static const int gui_emblem_width = {width}, gui_emblem_height = {height};"]
    for name, data in blobs.items():
        lines.append(f"static const unsigned char {name}[] = {{")
        lines.extend("    " + ",".join(str(b) for b in data[i:i + 24]) + "," for i in range(0, len(data), 24))
        lines.append("};")
    lines.append("#endif")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
