"""Convert the vendored Spleen cells (ASCII/Latin-1) to original C row tables."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZES = ((8, 16), (12, 24), (16, 32), (32, 64))


def generate():
    out = ['/* Generated by tools/spleen_header.py; Spleen 2.2.0, BSD-2-Clause. */',
           '/* See third_party/spleen/LICENSE. Rows are left-aligned in uint32_t. */']
    for width, height in SIZES:
        lines = (ROOT / f'third_party/spleen/spleen-{width}x{height}.bdf').read_text().splitlines()
        glyphs = {}
        for i, line in enumerate(lines):
            if line.startswith('ENCODING '):
                code = int(line.split()[1])
            elif line == 'BITMAP':
                rows = lines[i + 1:lines.index('ENDCHAR', i)]
                if 32 <= code <= 255:
                    assert len(rows) == height
                    glyphs[code] = [int(row, 16) << (32 - len(row) * 4) for row in rows]
        out.append(f'static const uint32_t spleen_{height}[224][{height}] = {{')
        for code in range(32, 256):
            out.append('    {' + ','.join(f'0x{row:08x}' for row in glyphs.get(code, glyphs[63])) + '},')
        out.append('};')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'backends/host/osd_font.h')
    args = parser.parse_args()
    args.output.write_text(generate())
