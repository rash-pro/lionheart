/* Host-only asset conversion keeps target binaries out of the build pipeline. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define STBI_ONLY_ZLIB
#define STBI_SUPPORT_ZLIB
#define STBI_NO_HDR
#define STBI_NO_LINEAR
#define STB_IMAGE_IMPLEMENTATION
#include "stb_image.h"

static void fail(const char *why) { fprintf(stderr, "assetgen: %s\n", why); exit(1); }
static unsigned char *read_file(const char *root, const char *name, size_t *size)
{
    char path[4096];
    if (snprintf(path, sizeof(path), "%s/%s", root, name) >= (int)sizeof(path)) fail("path too long");
    FILE *f = fopen(path, "rb");
    if (!f || fseek(f, 0, SEEK_END)) fail(path);
    long n = ftell(f);
    if (n < 0 || fseek(f, 0, SEEK_SET)) fail("cannot size input");
    unsigned char *data = malloc((size_t)n + 1);
    if (!data || fread(data, 1, (size_t)n, f) != (size_t)n) fail("cannot read input");
    fclose(f); data[n] = 0; *size = (size_t)n; return data;
}
static uint32_t be32(const unsigned char *p)
{ return (uint32_t)p[0]<<24 | (uint32_t)p[1]<<16 | (uint32_t)p[2]<<8 | p[3]; }
static void blob(FILE *out, const char *name, const unsigned char *data, size_t n)
{
    fprintf(out, "static const unsigned char %s[] = {\n", name);
    for (size_t i = 0; i < n; ++i) {
        if (i % 24 == 0) fputs("    ", out);
        fprintf(out, "%u,", data[i]);
        if (i % 24 == 23 || i + 1 == n) fputc('\n', out);
    }
    fputs("};\n", out);
}
static void gui(FILE *out, const char *root)
{
    size_t n, compressed = 0; unsigned char *png = read_file(root, "assets/branding/icon-128.png", &n);
    if (n < 33 || memcmp(png, "\211PNG\r\n\032\n", 8)) fail("expected PNG");
    uint32_t w = be32(png+16), h = be32(png+20);
    if (!w || !h || png[24] != 8 || (png[25] != 2 && png[25] != 6) || png[28]) fail("expected noninterlaced RGB/RGBA8");
    size_t channels = png[25] == 6 ? 4 : 3, stride = (size_t)w * channels;
    if (stride > 0x7fffffff / h - 1 || n > 0x7fffffff) fail("image too large");
    unsigned char *chunks = malloc(n);
    if (!chunks) fail("allocation failed");
    for (size_t at = 8; at + 12 <= n;) {
        uint32_t len = be32(png+at);
        if (len > n - at - 12) fail("truncated PNG");
        if (!memcmp(png+at+4, "IDAT", 4)) { memcpy(chunks+compressed, png+at+8, len); compressed += len; }
        at += (size_t)len + 12;
    }
    int raw_n;
    unsigned char *raw = (unsigned char *)stbi_zlib_decode_malloc((char *)chunks, (int)compressed, &raw_n);
    if (!raw || (size_t)raw_n < h*(stride+1)) fail("invalid compressed pixels");
    unsigned char *pixels = malloc((size_t)w*h*4);
    if (!pixels) fail("allocation failed");
    for (size_t y = 0; y < h; ++y) {
        unsigned char *row = raw+y*(stride+1)+1;
        unsigned char *prev = y ? row-stride-1 : NULL;
        int mode = row[-1];
        if (mode > 4) fail("invalid PNG filter");
        for (size_t x = 0; x < stride; ++x) {
            int left = x >= channels ? row[x-channels] : 0, up = prev ? prev[x] : 0;
            int ul = prev && x >= channels ? prev[x-channels] : 0, v = 0;
            if (mode == 1) v = left;
            if (mode == 2) v = up;
            if (mode == 3) v = (left+up)/2;
            if (mode == 4) {
                int p = left+up-ul, a = abs(p-left), b = abs(p-up), c = abs(p-ul);
                v = a <= b && a <= c ? left : b <= c ? up : ul;
            }
            row[x] = (unsigned char)(row[x]+v);
        }
        for (size_t x = 0; x < w; ++x) {
            unsigned char *dst = pixels+(y*w+x)*4;
            memcpy(dst, row+x*channels, 3); dst[3] = channels == 4 ? row[x*channels+3] : 255;
        }
    }
    fputs("/* Generated by tools/embed_gui_assets.py; source notices accompany vendored assets. */\n#ifndef FF8_GUI_ASSETS_H\n#define FF8_GUI_ASSETS_H\n", out);
    fprintf(out, "static const int gui_emblem_width = %u, gui_emblem_height = %u;\n", w, h);
    size_t font_n; unsigned char *font = read_file(root, "third_party/chakra-petch/ChakraPetch-Regular.ttf", &font_n);
    blob(out, "gui_font_regular", font, font_n); free(font);
    font = read_file(root, "third_party/chakra-petch/ChakraPetch-SemiBold.ttf", &font_n);
    blob(out, "gui_font_semibold", font, font_n); free(font);
    blob(out, "gui_emblem_rgba", pixels, (size_t)w*h*4); fputs("#endif\n", out);
    free(png); free(chunks); free(raw); free(pixels);
}
static void spleen(FILE *out, const char *root)
{
    const int widths[] = {8,12,16,32}, heights[] = {16,24,32,64};
    fputs("/* Generated by tools/spleen_header.py; Spleen 2.2.0, BSD-2-Clause. */\n/* See third_party/spleen/LICENSE. Rows are left-aligned in uint32_t. */\n", out);
    for (int s = 0; s < 4; ++s) {
        char name[128]; size_t n; uint32_t glyphs[224][64] = {{0}}; int present[224] = {0};
        snprintf(name, sizeof(name), "third_party/spleen/spleen-%dx%d.bdf", widths[s], heights[s]);
        unsigned char *data = read_file(root, name, &n); int code = -1;
        for (char *line = strtok((char *)data, "\r\n"); line; line = strtok(NULL, "\r\n")) {
            if (!strncmp(line, "ENCODING ", 9)) code = atoi(line+9);
            if (!strcmp(line, "BITMAP")) {
                int row = 0;
                while ((line = strtok(NULL, "\r\n")) && strcmp(line, "ENDCHAR")) {
                    size_t digits = strlen(line);
                    if (digits > 8 || row >= heights[s]) fail("invalid BDF bitmap");
                    if (code >= 32 && code <= 255) glyphs[code-32][row] = (uint32_t)strtoul(line, NULL, 16) << (32-digits*4);
                    ++row;
                }
                if (code >= 32 && code <= 255) { if (row != heights[s]) fail("invalid BDF height"); present[code-32] = 1; }
            }
        }
        if (!present[63-32]) fail("missing fallback glyph");
        fprintf(out, "static const uint32_t spleen_%d[224][%d] = {\n", heights[s], heights[s]);
        for (int c = 0; c < 224; ++c) {
            fputs("    {", out);
            for (int r = 0; r < heights[s]; ++r) fprintf(out, "%s0x%08x", r ? "," : "", (unsigned)glyphs[present[c] ? c : 63-32][r]);
            fputs("},\n", out);
        }
        fputs("};\n", out); free(data);
    }
}
int main(int argc, char **argv)
{
    if (argc != 4 || (strcmp(argv[1], "gui") && strcmp(argv[1], "spleen"))) fail("usage: assetgen gui|spleen SOURCE_ROOT OUTPUT");
    FILE *out = fopen(argv[3], "w"); if (!out) fail("cannot open output");
    if (!strcmp(argv[1], "gui")) gui(out, argv[2]); else spleen(out, argv[2]);
    if (ferror(out) || fclose(out)) fail("cannot write output");
    return 0;
}
